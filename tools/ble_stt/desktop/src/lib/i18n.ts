export type Translator = (key: string, fallback?: string) => string

export function normalizeLanguage(value: string | null | undefined): LanguageCode {
  if (value === "zh-CN" || value?.toLowerCase().startsWith("zh")) {
    return "zh-CN"
  }
  return "en"
}

export function detectInitialLanguage(): LanguageCode {
  if (typeof window === "undefined") {
    return "en"
  }

  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY)
    if (stored) {
      return normalizeLanguage(stored)
    }
  } catch {
    // Ignore storage failures and fall back to the browser language.
  }

  return normalizeLanguage(window.navigator.language)
}

export function persistLanguage(language: LanguageCode) {
  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language)
  } catch {
    // Storage can be unavailable in restricted contexts; the in-memory choice still works.
  }
}

export function createTranslator(language: LanguageCode): Translator {
  return (key: string, fallback?: string) => {
    const normalizedKey = key as TranslationKey
    return (
      translations[language][normalizedKey] ??
      translations.en[normalizedKey] ??
      fallback ??
      key
    )
  }
}
